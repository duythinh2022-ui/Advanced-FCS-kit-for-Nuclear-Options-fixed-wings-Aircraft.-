# writes Vortex_FS20.FCS/VaneBoxData.cs from gen.py (frame in the lift fan part's local frame; each vane pair in its hinge frame)
import sys; sys.path.insert(0, '/home/claude/work/geo')
import numpy as np, gen
o = gen.build(); org = o['org']
def fl(a, nd):
    a = np.asarray(a, float).ravel(); s = []
    for i in range(0, len(a), 12):
        s.append('\t\t\t\t' + ', '.join((f"{v:.{nd}f}".rstrip('0').rstrip('.') if abs(v) > 0.5 * 10 ** -nd else '0') + 'f' for v in a[i:i + 12]) + ',')
    return '\n'.join(s).rstrip(',')
def ints(a, per=24):
    a = np.asarray(a).ravel(); s = []
    for i in range(0, len(a), per): s.append('\t\t\t\t' + ', '.join(str(int(v)) for v in a[i:i + per]) + ',')
    return '\n'.join(s).rstrip(',')
FP, FN, FUV, FC, FT = o['frame']
FPl = np.round(FP - org, 4)
hinges = [np.round(np.array([0.0, gen.YH, gen.ZC + dz]) - org, 4) for dz, k in o['pairs']]
def block(name, typ, arrs, f):
    body = ',\n'.join('\t\t\tnew ' + typ + '[]\n\t\t\t{\n' + f(a) + '\n\t\t\t}' for a in arrs)
    return f"\t\tprivate static readonly {typ}[][] {name} = new {typ}[][]\n\t\t{{\n{body}\n\t\t}};"
VP = [np.round(v[0], 4) for v in o['vanes']]
assert all(len(set(v[3][:, 0].tolist())) == 1 for v in o['vanes'])
out = f'''using UnityEngine;

namespace Vortex_FS20.FCS
{{
	// Vortex 0.5.1 (0.5.5: frame in two submeshes): the vane box's meshes. Generated by tools/vanebox/gen.py (export_cs.py) from the dimensions in VaneBox.cs's
	// header; do not edit by hand. Frame: positions in the lift fan part's local frame (the part sits at {org[0]:.4f}, {org[1]:.4f},
	// {org[2]:.4f} of the airframe, not turned). Vane pairs: each in its hinge frame (x along the hinge, y up, z forward, chord
	// along y); {len(VP)} meshes for the {len(hinges)} pairs (the tips differ with the frame's shape where the pair hangs).
	// Triangles wound as the game's meshes (cross(v1 - v0, v2 - v0) along the normal).
	internal sealed partial class VaneBox
	{{
		// vertex count of the fan part mesh the dimensions were measured on (the game as installed on 18 Nov 2026)
		internal const int FanMeshVerts = 3720;

		internal static readonly Vector3[] HingeLocal = new Vector3[]
		{{
{chr(10).join(f"			new Vector3({h[0]:.4f}f, {h[1]:.4f}f, {h[2]:.4f}f)," for h in hinges).rstrip(',')}
		}};

		// which vane mesh each pair uses
		internal static readonly int[] PairMesh = new int[] {{ {', '.join(str(k) for _, k in o['pairs'])} }};

		private static readonly float[] FrameP = new float[]
		{{
{fl(FPl, 4).replace(chr(9) * 4, chr(9) * 3)}
		}};

		private static readonly float[] FrameN = new float[]
		{{
{fl(FN, 4).replace(chr(9) * 4, chr(9) * 3)}
		}};

		// (7 decimals: the skin faces map onto a few texels, their uv steps are 1e-5..1e-3)
		private static readonly float[] FrameUV = new float[]
		{{
{fl(FUV, 7).replace(chr(9) * 4, chr(9) * 3)}
		}};

		// vertex colour (grey level): 255 as the bay doors' inner structure (and on the skin faces, as the game's), 99 as the
		// fan duct wall
		private static readonly byte[] FrameC = new byte[]
		{{
{ints(FC[:, 0], 31).replace(chr(9) * 4, chr(9) * 3)}
		}};

		// Vortex 0.5.5: FrameT's first FrameSkinStart indices are the structure faces (submesh 0, aircraft_structure), the rest
		// the outward faces drawn with the fan part's skin like the bay's bevel round the exit (submesh 1)
		internal const int FrameSkinStart = {o['frame_split']};

		private static readonly ushort[] FrameT = new ushort[]
		{{
{ints(FT).replace(chr(9) * 4, chr(9) * 3)}
		}};

{block('VaneP', 'float', VP, lambda a: fl(a, 4))}

{block('VaneN', 'float', [v[1] for v in o['vanes']], lambda a: fl(a, 4))}

{block('VaneUV', 'float', [v[2] for v in o['vanes']], lambda a: fl(a, 5))}

		private const byte VaneC = {int(o['vanes'][0][3][0, 0])};

{block('VaneT', 'ushort', [v[4] for v in o['vanes']], lambda a: ints(a))}
	}}
}}
'''
open(sys.argv[1] if len(sys.argv) > 1 else '/tmp/VaneBoxData.cs', 'w').write(out)
tot = len(FT) + sum(len(o['vanes'][k][4]) for _, k in o['pairs'])
print('written', len(out), 'chars; frame', len(FPl), 'verts', len(FT), 'tris; vane meshes', [(len(v[0]), len(v[4])) for v in o['vanes']], '; pairs', len(hinges), '; triangles in all', tot, '; frame colours', sorted(set(FC[:, 0].tolist())))
