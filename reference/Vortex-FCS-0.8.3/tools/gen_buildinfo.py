#!/usr/bin/env python3
"""gen_buildinfo.py <srcdir> <nativedir>: writes <srcdir>/FcsBuildInfo.cs.
Vortex 0.7.1 FCS hand-over (FamilyCompat.Decide): FamilyFingerprint = sha256 over every C# source file of the plugin (sorted by
relative path, CRLF -> LF) and the native core's Rust source (src/*.rs, Cargo.toml), leaving out FcsBuildInfo.cs, FcsVersion.cs and
whatever <srcdir>/family-fingerprint-exclude.txt lists (files that never act on a family jet). The FS-20 Vortex FCS and the FS-20
Vortex Family FCS are built from the same tree, so the same tree gives the same fingerprint in both.
0.7.2: inside a C# file, the lines from a line containing  // FAMILY-FP EXCLUDE BEGIN  to a line containing  // FAMILY-FP EXCLUDE END
(both marker lines included) are left out too: B-only code in a shared file. Not nested; an unbalanced marker stops the build. Nothing
checks that the marked code never runs on a family jet - guard it yourself (e.g. FamilyCompat.VariantOf(a) == Variant.B). A file
without markers hashes exactly as in 0.7.1."""
import hashlib, os, sys
src, nat = sys.argv[1], sys.argv[2]
excl = {'FcsBuildInfo.cs', 'FcsVersion.cs'}
ef = os.path.join(src, 'family-fingerprint-exclude.txt')
if os.path.exists(ef):
    for l in open(ef, encoding='utf-8'):
        l = l.split('#')[0].strip()
        if l: excl.add(l.replace('\\', '/'))
files = []
for root, dirs, fs in os.walk(src):
    dirs[:] = [d for d in dirs if d not in ('obj', 'bin', 'bench', 'DevUnlock', 'tools')]
    for f in fs:
        if f.endswith('.cs'):
            rel = os.path.relpath(os.path.join(root, f), src).replace(os.sep, '/')
            if rel not in excl: files.append(('cs/' + rel, os.path.join(root, f)))
for rel in ('Cargo.toml',):
    p = os.path.join(nat, rel)
    if os.path.exists(p): files.append(('rs/' + rel, p))
for f in sorted(os.listdir(os.path.join(nat, 'src'))):
    if f.endswith('.rs'): files.append(('rs/src/' + f, os.path.join(nat, 'src', f)))
BEGIN, END = b'// FAMILY-FP EXCLUDE BEGIN', b'// FAMILY-FP EXCLUDE END'
def strip_marked(rel, b):
    if BEGIN not in b and END not in b:
        return b, 0
    out, inside, n, start = [], False, 0, 0
    for i, line in enumerate(b.split(b'\n'), 1):
        if BEGIN in line:
            if inside: sys.exit(f'gen_buildinfo: {rel}:{i}: FAMILY-FP EXCLUDE BEGIN inside a block opened at line {start}')
            inside, start = True, i; continue
        if END in line:
            if not inside: sys.exit(f'gen_buildinfo: {rel}:{i}: FAMILY-FP EXCLUDE END without BEGIN')
            inside = False; n += 1; continue
        if not inside: out.append(line)
    if inside: sys.exit(f'gen_buildinfo: {rel}:{start}: FAMILY-FP EXCLUDE BEGIN never closed')
    return b'\n'.join(out), n
h = hashlib.sha256()
blocks = 0
for rel, p in sorted(files):
    b = open(p, 'rb').read().replace(b'\r\n', b'\n')
    if rel.startswith('cs/'):
        b, k = strip_marked(rel, b)
        if k: print(f'  {rel[3:]}: {k} B-only block(s) left out'); blocks += k
    h.update(rel.encode() + b'\0' + str(len(b)).encode() + b'\0' + b)
fp = h.hexdigest()
open(os.path.join(src, 'FcsBuildInfo.cs'), 'w', encoding='utf-8', newline='\n').write(
f'''namespace Vortex_FS20.FCS
{{
	// generated by tools/gen_buildinfo.py - do not edit. FamilyCompat.Decide compares this with the other FS-20 Vortex FCS plugin's.
	internal static class FcsBuildInfo
	{{
		public static readonly string FamilyFingerprint = "{fp}";

		public const int FamilyFiles = {len(files)};

		// 0.7.3: hand-over rule. 1 (0.7.1-0.7.2): same fingerprint -> the FS-20 Vortex FCS flies the family jets. 2 (0.7.3): the Family FCS
		// flies the family jets whenever it is loaded, with its own settings; the fingerprint is only logged.
		public static readonly int HandOverRule = 2;
	}}
}}
''')
print(f'FamilyFingerprint {fp[:16]} over {len(files)} files' + (f', {blocks} B-only block(s) left out' if blocks else ''))
