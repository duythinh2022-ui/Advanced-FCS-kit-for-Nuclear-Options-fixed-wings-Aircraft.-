#!/bin/bash
# axrun.sh <tag> [args] : climb / side / lever / pedal combinations on Tom's jet (13.8 t), csv in /tmp/ax
tag=$1; shift; cd /home/claude/vortex; export OUT=/tmp/ax; mkdir -p $OUT
B='pitch=0:0,8:0,8.3:0.6,14:0.6,14.3:0'
r(){ n=$1; shift; ./tom.sh ${n}_$tag T=38 "$@" "${X[@]}"; }
X=("$@")
( r C0  "$B,20.5:0,20.6:1,27:1,27.1:0" ) &
( r S0  "roll=0:0,21:0,21.1:1,27:1,27.1:0" ) &
( r Sh  "roll=0:0,21:0,21.1:0.4,27:0.4,27.1:0" ) &
( r F0  "thr=0:0,21:0,21.1:0.5,27:0.5,27.1:0.2" ) &
wait
( r CS5 "$B,20.5:0,20.6:1,27:1,27.1:0" "roll=0:0,21:0,21.1:1,27:1,27.1:0" ) &
( r CS0 "$B,21:0,21.1:1,27:1,27.1:0" "roll=0:0,21:0,21.1:1,27:1,27.1:0" ) &
( r SC5 "$B,21.5:0,21.6:1,27:1,27.1:0" "roll=0:0,21:0,21.1:1,27:1,27.1:0" ) &
( r CSh "$B,20.5:0,20.6:1,27:1,27.1:0" "roll=0:0,21:0,21.1:0.4,27:0.4,27.1:0" ) &
wait
( r CF5 "$B,20.5:0,20.6:1,27:1,27.1:0" "thr=0:0,21:0,21.1:0.5,27:0.5,27.1:0.2" ) &
( r CY5 "$B,20.5:0,20.6:1,27:1,27.1:0" "yaw=0:0,21:0,21.1:1,24:1,24.1:0" ) &
( r SCS "$B,20.5:0,20.6:1,24:1,24.1:0" "roll=0:0,21:0,21.1:1,29:1,29.1:0" ) &    # side stick held through a climb stop
( r SD  "pitch=0:0,8:0,8.3:1,16:1,16.3:0,24:0,24.1:-1,27:-1,27.1:0" "roll=0:0,21:0,21.1:1,29:1,29.1:0" ) &    # side stick held through a descent and its stop
wait
