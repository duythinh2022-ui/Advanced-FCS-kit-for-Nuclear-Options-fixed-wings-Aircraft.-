#!/usr/bin/env python3
"""Generate docs/CONFIG_REFERENCE.md: every BepInEx config key of the six reference FCS plugins, side by side.

usage: python3 tools/gen_config_reference.py [kit_root]

It reads each reference tree's <Namespace>.FCS/Plugin.cs, finds every `cfg.Bind(...)` (player file) and `dev.Bind(...)`
(Dev file, only editable with the DevUnlock DLL installed), and writes one table per config section with the default of
each jet and the description text (from the first jet that has the key). Re-run it after changing Plugin.cs.
"""
import os, re, sys, glob

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..")
JETS = [("F-22E", "reference/F22E-FCS-4.3.0/Aryx_F22E_StrikeRaptor.FCS/Plugin.cs"),
        ("Ifrit", "reference/Ifrit-FCS-1.3.0/Ifrit_KR67.FCS/Plugin.cs"),
        ("Revoker", "reference/Revoker-FCS-1.4.1/Revoker_FS12.FCS/Plugin.cs"),
        ("Compass", "reference/Compass-FCS-0.5.0/Compass_TA30.FCS/Plugin.cs"),
        ("Ternion", "reference/Ternion-FCS-0.4.0/Ternion_FS3.FCS/Plugin.cs"),
        ("Su-30", "reference/Su30-FCS-0.6.0/Su30_VXN.FCS/Plugin.cs")]


def split_args(s, i):
    """s[i] is just after '(' ; return (list of raw args, index after ')')."""
    args, depth, cur, j = [], 0, [], i
    while j < len(s):
        c = s[j]
        if c == '"':                                   # C# string (regular or verbatim)
            verb = j > 0 and s[j - 1] == '@'
            k = j + 1
            while k < len(s):
                if s[k] == '\\' and not verb:
                    k += 2; continue
                if s[k] == '"':
                    if verb and k + 1 < len(s) and s[k + 1] == '"':
                        k += 2; continue
                    break
                k += 1
            cur.append(s[j:k + 1]); j = k + 1; continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            if depth == 0:
                args.append("".join(cur).strip()); return args, j + 1
            depth -= 1
        elif c == ',' and depth == 0:
            args.append("".join(cur).strip()); cur = []; j += 1; continue
        cur.append(c); j += 1
    return args, j


def unq(a):
    a = a.strip()
    a = re.sub(r'^\w+:\s*', '', a)                     # named argument (defaultValue: true)
    m = re.findall(r'"((?:[^"\\]|\\.)*)"', a)
    if m and (a.startswith('"') or a.startswith('new ConfigDescription')):
        return " ".join(m).replace('\\"', '"')
    return a


def parse(path):
    s = open(path, encoding="utf-8-sig").read()
    out = []
    for m in re.finditer(r'\b(cfg|dev)\.Bind(?:<[^>]*>)?\(', s):
        args, _ = split_args(s, m.end())
        if len(args) < 3:
            continue
        sec, key = unq(args[0]), unq(args[1])
        d0 = unq(args[2])
        default = d0[:-1] if re.match(r'^-?[\d.]+(E[-+]?\d+)?f$', d0, re.I) else d0   # 30f -> 30, 2E-05f -> 2E-05
        desc = unq(args[3]) if len(args) > 3 else ""
        out.append((m.group(1), sec, key, default, desc))
    return out


def main():
    data = {}
    order = []
    for jet, rel in JETS:
        p = os.path.join(ROOT, rel)
        for file_, sec, key, default, desc in parse(p):
            k = (sec, key)
            if k not in data:
                data[k] = {"file": file_, "desc": desc, "def": {}}
                order.append(k)
            data[k]["def"][jet] = default
            if not data[k]["desc"] and desc:
                data[k]["desc"] = desc
    secs = []
    for sec, _ in order:
        if sec not in secs:
            secs.append(sec)
    L = ["# Configuration reference (generated)", "",
         "Generated by `tools/gen_config_reference.py` from each reference tree's `Plugin.cs`. Do not edit by hand.", "",
         "- **File** `player` = `BepInEx/config/<plugin GUID>.cfg` (what every player sees); `dev` = the Dev file, editable only with the",
         "  optional DevUnlock DLL installed (otherwise the defaults below are used).",
         "- **—** = the key does not exist on that jet. Values are the *code defaults*; a config file written by an older version can hold",
         "  something else (some keys are force-migrated once, see the description).",
         "- Descriptions are the in-code text of the first jet that has the key, cut to 300 characters; open `Plugin.cs` for the rest.", ""]
    jets = [j for j, _ in JETS]
    for sec in secs:
        L += [f"## {sec}", "", "| Key | File | " + " | ".join(jets) + " | Description |", "|---|---|" + "---|" * len(jets) + "---|"]
        for k in order:
            if k[0] != sec:
                continue
            d = data[k]
            vals = [d["def"].get(j, "—").replace("|", "\\|") for j in jets]
            desc = d["desc"].replace("|", "\\|").replace("\n", " ")
            if len(desc) > 300:
                desc = desc[:297] + "..."
            L.append(f"| `{k[1]}` | {d['file'].replace('cfg', 'player')} | " + " | ".join(vals) + f" | {desc} |")
        L.append("")
    n = len(order)
    L.insert(4, f"{n} keys in {len(secs)} sections across the six jets.\n")
    out = os.path.join(ROOT, "docs", "CONFIG_REFERENCE.md")
    open(out, "w").write("\n".join(L))
    print(f"wrote {out}: {n} keys, {len(secs)} sections")


if __name__ == "__main__":
    main()
